#!/usr/bin/env node
// Keeps the icon map's derived parts in step with the curated set, and writes MAPPING.md.
//
//   node codemod/sync.mjs           rewrite material-to-carbon.json (derived keys only) and MAPPING.md
//   node codemod/sync.mjs --check   write nothing; exit 1 if either file is stale or the map is wrong
//
// Hand-edited in material-to-carbon.json: the name entries, `_notes`, `_usage`, `_about`, `_carbon`.
// Derived here: `_curated` (every name Icon can draw, from src/icons/names.json) and `_same_word`
// (Material names that are also curated Carbon names with a different drawing; the codemod lists
// those when it finds one outside an icon position, because the type checker cannot).
// Not shipped: this script needs src/, which is not in the tarball.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const mapFile = path.join(here, "material-to-carbon.json")
const mdFile = path.join(here, "MAPPING.md")
const namesFile = path.join(here, "..", "src", "icons", "names.json")
const check = process.argv.includes("--check")

const problems = []
const map = JSON.parse(fs.readFileSync(mapFile, "utf8"))
const groups = JSON.parse(fs.readFileSync(namesFile, "utf8"))
const curated = Object.entries(groups)
  .filter(([group]) => !group.startsWith("$"))
  .flatMap(([, list]) => list)
  .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
const curatedSet = new Set(curated)

const names = Object.keys(map).filter((key) => !key.startsWith("_"))
const sorted = [...names].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
if (names.join() !== sorted.join()) problems.push("the names in material-to-carbon.json are not in order")
for (const name of names) {
  const to = map[name]
  if (!/^[a-z0-9]+(_[a-z0-9]+)*$/.test(name)) problems.push(`"${name}" is not a Material Symbols name`)
  if (to === null) {
    if (!map._notes?.[name]) problems.push(`"${name}" maps to null and has no note saying why`)
  } else if (typeof to !== "string") problems.push(`"${name}" must map to a name or null`)
  else if (!curatedSet.has(to)) problems.push(`"${name}" maps to "${to}", which is not in src/icons/names.json`)
}
for (const name of Object.keys(map._notes ?? {})) if (!names.includes(name)) problems.push(`_notes has "${name}", which is not in the map`)
for (const name of groups.figma ?? []) if (!curatedSet.has(name)) problems.push(`Figma's "${name}" is missing from the curated set`)

const sameWord = sorted.filter((name) => curatedSet.has(name) && map[name] !== name)

const next = {
  _about: map._about,
  _carbon: map._carbon,
  _curated: curated,
  _same_word: sameWord,
  _notes: Object.fromEntries(sorted.filter((n) => map._notes?.[n]).map((n) => [n, map._notes[n]])),
  _usage: Object.fromEntries(sorted.filter((n) => map._usage?.[n]).map((n) => [n, map._usage[n]])),
  ...Object.fromEntries(sorted.map((n) => [n, map[n]])),
}
const nextJson = JSON.stringify(next, null, 2).replace(/"_curated": \[[^\]]*\]/, () => `"_curated": ${JSON.stringify(curated)}`).replace(/"_same_word": \[[^\]]*\]/, () => `"_same_word": ${JSON.stringify(sameWord)}`) + "\n"

// ── MAPPING.md ──────────────────────────────────────────────────────────────────────────────────
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|")
const code = (s) => `\`${s}\``
const unmapped = sorted.filter((n) => map[n] === null)
const targets = new Set(sorted.map((n) => map[n]).filter(Boolean))
const md = `# Material Symbols → Carbon: the icon map

_Generated by \`node packages/ui/codemod/sync.mjs\` from [material-to-carbon.json](material-to-carbon.json). Edit the JSON, not this file._

${sorted.length} Material names are mapped: ${sorted.length - unmapped.length} to ${targets.size} Carbon icons, ${unmapped.length} to nothing. Carbon names are the svg names in ${map._carbon} (Apache-2.0).

How each target was chosen: the Carbon icon with the same **meaning**. Where the Figma file or an app's spec already draws a place with a Carbon icon, that icon is used. When Carbon has no honest match, the name maps to nothing and the note says what to do. There are no sparkle icons.

"Where used" counts string literals in icon positions on 2026-11-13: \`ui\` and \`playground\` are this repo; Lockdown also counts the icon names its Rust templates carry.

## Run it

\`\`\`bash
npx unicron-codemod icons apps/web/src --dry   # see what would change
npx unicron-codemod icons apps/web/src         # write it
\`\`\`

Run it **once**, on a clean tree, and read the diff. A second run would rename names that exist in both sets (\`error\` becomes \`warning\`, and \`warning\` would then become \`warning--alt\`), so the tool refuses when it finds Carbon names already in place.

## No Carbon match (${unmapped.length})

| Material | Where used | What to do |
|---|---|---|
${unmapped.map((n) => `| ${code(n)} | ${cell(map._usage?.[n])} | ${cell(map._notes?.[n])} |`).join("\n")}

An app can add its own glyph for one of these with \`registerIcons()\` from \`@unicron/ui\`, and name it in the \`UnicronIconRegistry\` interface so it type-checks.

## Same word, different drawing (${sameWord.length})

These Material names are also names in the curated Carbon set, but the right Carbon icon has another name. The type checker accepts the old name, so a use the codemod could not reach compiles and draws the wrong thing. The codemod lists every such use it leaves.

| Material | Becomes | Carbon's icon of the old name is |
|---|---|---|
${sameWord.map((n) => `| ${code(n)} | ${map[n] === null ? "nothing" : code(map[n])} | ${cell(SAME_WORD_NOTE(n))} |`).join("\n")}

## The map (${sorted.length})

| Material | Carbon | Where used | Note |
|---|---|---|---|
${sorted.map((n) => `| ${code(n)} | ${map[n] === null ? "none" : code(map[n])} | ${cell(map._usage?.[n])} | ${cell(map._notes?.[n])} |`).join("\n")}
`

function SAME_WORD_NOTE(name) {
  const drawn = {
    error: "a slashed circle (reads as blocked)",
    pin: "a pushpin",
    rule: "a shield with lines",
    send: "a paper plane pointing right (kept for a Sent folder)",
    snooze: "an alarm clock with a z",
    stop: "an empty square",
    timer: "a stopwatch",
    warning: "a circle with an exclamation mark",
  }
  return drawn[name] ?? "a variant of the same idea"
}

if (problems.length) {
  for (const problem of problems) console.error(`icon map: ${problem}`)
  process.exit(1)
}
if (check) {
  const stale = []
  if (fs.readFileSync(mapFile, "utf8") !== nextJson) stale.push(path.basename(mapFile))
  if (!fs.existsSync(mdFile) || fs.readFileSync(mdFile, "utf8") !== md) stale.push(path.basename(mdFile))
  if (stale.length) {
    console.error(`icon map: ${stale.join(" and ")} ${stale.length > 1 ? "are" : "is"} stale. Run \`node packages/ui/codemod/sync.mjs\` and commit the result.`)
    process.exit(1)
  }
  console.log(`✓ icon map is current (${sorted.length} names, ${unmapped.length} unmapped, ${curated.length} curated)`)
} else {
  fs.writeFileSync(mapFile, nextJson)
  fs.writeFileSync(mdFile, md)
  console.log(`✓ wrote ${path.basename(mapFile)} and ${path.basename(mdFile)} (${sorted.length} names, ${unmapped.length} unmapped, ${sameWord.length} same-word)`)
}
