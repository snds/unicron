#!/usr/bin/env node
// unicron-sources: writes the stylesheet entry for an app that wants classes only for the
// @unicron/ui modules it uses.
//
//   unicron-sources <out.css> <module> [<module> …]
//   unicron-sources src/unicron.css button dialog app-frame security/code-display
//
// A module is what an app imports: `button` for `@unicron/ui/button` (or for `Button` from the
// package root), `security/code-display`, `icon`. Run it again when the list changes.
//
// Why a list of what to leave out: `@unicron/ui/styles` tells Tailwind to scan every component in
// the package, so an app pays for the classes of all of them. `styles/lean.css` is the same
// stylesheet without that line. Tailwind (4.3) does not narrow a scan inside node_modules to
// single files, but it does honour `@source not`. So the file this writes scans the package's
// components and leaves out every file the named modules do not reach. A module left off the list
// loses its classes, so list everything the app imports; a module that is listed brings the files
// it imports with it (dist/styles/sources.json holds that map).
//
// Node built-ins only.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

/**
 * The stylesheet's text. `sources` is dist/styles/sources.json's `modules` map, `rel` the path from
 * the stylesheet's folder to the package's dist folder, with forward slashes.
 */
export function sourcesCss({ modules, sources, rel }) {
  const unknown = modules.filter((name) => !(name in sources))
  if (unknown.length) throw new Error(`not a module of @unicron/ui: ${unknown.join(", ")}`)
  const used = new Set(modules.flatMap((name) => sources[name]))
  const all = [...new Set(Object.values(sources).flat())].sort()
  const left = all.filter((file) => !used.has(file))
  const base = rel.replace(/\/$/, "")
  // `button.js` and the files tsc wrote beside it (its types and maps), in one pattern.
  const beside = (file) => `${file.replace(/\.js$/, "")}.*`
  return [
    `/* Generated by unicron-sources. Do not edit: run it again when the list changes. */`,
    `/* Modules: ${[...modules].sort().join(", ")} */`,
    `@import "@unicron/ui/styles/lean.css";`,
    `@source "${base}/components";`,
    `@source "${base}/lib";`,
    ...left.map((file) => `@source not "${base}/${beside(file)}";`),
    "",
  ].join("\n")
}

/** The path from `fromDir` to the package's dist, through the app's own node_modules when it has one. */
export function distPathFrom(fromDir, packageDir) {
  for (let dir = path.resolve(fromDir); ; dir = path.dirname(dir)) {
    const installed = path.join(dir, "node_modules", "@unicron", "ui")
    if (fs.existsSync(path.join(installed, "dist"))) return path.relative(fromDir, path.join(installed, "dist")).split(path.sep).join("/")
    if (dir === path.dirname(dir)) break
  }
  return path.relative(fromDir, path.join(packageDir, "dist")).split(path.sep).join("/")
}

function main(argv) {
  const [out, ...modules] = argv
  if (!out || modules.length === 0 || out === "-h" || out === "--help") {
    console.log("unicron-sources <out.css> <module> [<module> …]\n\nWrites a stylesheet entry that makes Tailwind classes only for the @unicron/ui modules named.\nImport the file it writes instead of @unicron/ui/styles. Modules: dist/styles/sources.json.")
    process.exit(out && modules.length === 0 && out !== "-h" && out !== "--help" ? 1 : 0)
  }
  const packageDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
  const mapFile = path.join(packageDir, "dist", "styles", "sources.json")
  if (!fs.existsSync(mapFile)) {
    console.error(`unicron-sources: ${mapFile} is missing (build @unicron/ui first)`)
    process.exit(1)
  }
  const sources = JSON.parse(fs.readFileSync(mapFile, "utf8")).modules
  const outFile = path.resolve(out)
  let css
  try {
    css = sourcesCss({ modules, sources, rel: distPathFrom(path.dirname(outFile), packageDir) })
  } catch (error) {
    console.error(`unicron-sources: ${error.message}`)
    process.exit(1)
  }
  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, css)
  const left = css.split("\n").filter((line) => line.startsWith("@source not")).length
  console.log(`✓ wrote ${path.relative(process.cwd(), outFile)}: ${modules.length} module${modules.length === 1 ? "" : "s"}, ${left} files left out of the scan`)
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2))
