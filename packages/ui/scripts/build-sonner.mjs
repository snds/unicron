#!/usr/bin/env node
// Builds vendor/sonner.js: sonner's own module with one thing taken out, the <style> tag it adds
// to the page as it loads.
//
// Why: contract section 7 says no component may add a <style> tag at run time, because Lockdown's
// web vault runs with `style-src 'self'`. sonner (MIT) adds its stylesheet from its module's top
// level, so every page that loaded the Toaster got the tag, and a strict policy logged a refusal
// for it. The rules themselves already ship as a file: styles/index.css imports
// `sonner/dist/styles.css`. So the Toaster loads this copy, which is sonner's dist/index.mjs with
// the `__insertCSS` helper and its one call removed, and nothing else changed.
//
//   node scripts/build-sonner.mjs           write the file
//   node scripts/build-sonner.mjs --check   write nothing; exit 1 if the file on disk is stale
//
// The output is the same for the same sonner version. It is checked in (as the icon data is), so
// `pnpm test` fails when the installed sonner and the copy drift apart. The script stops, and says
// why, if sonner's module no longer has the shape it strips: then read sonner's new dist and
// update the two patterns below.

import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const outFile = path.join(root, "vendor", "sonner.js")
const check = process.argv.includes("--check")

const fail = (message) => {
  console.error(`build-sonner: ${message}`)
  process.exit(1)
}

const require = createRequire(import.meta.url)
const dist = path.dirname(require.resolve("sonner"))
const source = fs.readFileSync(path.join(dist, "index.mjs"), "utf8")
const { version } = JSON.parse(fs.readFileSync(path.join(dist, "..", "package.json"), "utf8"))

// The helper, from its first line to the brace that closes it at column 0.
const HELPER = /^function __insertCSS\(code\) \{\n[\s\S]*?\n\}\n/m
// Its one call: a whole line, the stylesheet as one string.
const CALL = /^__insertCSS\("(?:[^"\\]|\\.)*"\);?\n/m

const count = (pattern) => (source.match(new RegExp(pattern.source, "gm")) ?? []).length
if (count(HELPER) !== 1) fail(`expected one __insertCSS helper in sonner ${version}, found ${count(HELPER)}`)
if (count(CALL) !== 1) fail(`expected one __insertCSS call in sonner ${version}, found ${count(CALL)}`)

const stripped = source.replace(HELPER, "").replace(CALL, "")
if (stripped.includes("__insertCSS")) fail("__insertCSS is still in the output")
if (/createElement\(\s*['"]style['"]\s*\)/.test(stripped)) fail("the output still creates a <style> element")
if (!/^export \{ Toaster, toast, useSonner \};?\s*$/m.test(stripped)) fail(`sonner ${version} no longer exports { Toaster, toast, useSonner }`)

const USE_CLIENT = /^'use client';\n/
if (!USE_CLIENT.test(stripped)) fail(`sonner ${version} no longer starts with 'use client'`)

const header = `'use client';
// GENERATED by scripts/build-sonner.mjs from sonner ${version} (dist/index.mjs). Do not edit.
// The same module, less the <style> tag it adds to the page as it loads (contract section 7:
// strict CSP). Its rules ship as a file: styles/index.css imports sonner/dist/styles.css.
//
// sonner — MIT License — Copyright (c) 2023 Emil Kowalski
// Permission is hereby granted, free of charge, to any person obtaining a copy of this software
// and associated documentation files (the "Software"), to deal in the Software without
// restriction, including without limitation the rights to use, copy, modify, merge, publish,
// distribute, sublicense, and/or sell copies of the Software, and to permit persons to whom the
// Software is furnished to do so, subject to the following conditions: The above copyright notice
// and this permission notice shall be included in all copies or substantial portions of the
// Software. THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED,
// INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE
// AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM,
// DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
// OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.
`
const output = header + stripped.replace(USE_CLIENT, "")

if (check) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : null
  if (current !== output) fail(`vendor/sonner.js is stale against sonner ${version}. Run: pnpm --filter @unicron/ui sonner:build`)
  console.log(`✓ vendor/sonner.js is current (sonner ${version}, no <style> tag)`)
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, output)
  console.log(`✓ wrote vendor/sonner.js from sonner ${version} (${source.length - stripped.length} characters of stylesheet and helper removed)`)
}
