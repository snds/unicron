#!/usr/bin/env node
// tsc emits only TypeScript. The stylesheet ships from dist/ too (src/ is not in the published
// tarball), so copy src/styles → dist/styles after tsc. The relative `@source "../components"`
// inside index.css resolves the same way from either location (src/components or dist/components).
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const from = path.join(root, "src", "styles")
const to = path.join(root, "dist", "styles")
fs.rmSync(to, { recursive: true, force: true })
fs.cpSync(from, to, { recursive: true })
console.log(`✓ copied ${path.relative(root, from)} → ${path.relative(root, to)}`)

// ── The lean entry ──────────────────────────────────────────────────────────────────────────────
// index.css tells Tailwind to scan every component in the package (`@source "../components"`), so
// an app pays for the classes of all of them, used or not. lean.css is the same stylesheet without
// that one line: the app names the modules it imports with its own `@source` lines, and Tailwind
// makes classes for those only (docs/05-consuming.md → "A smaller stylesheet").
const SCAN_ALL = /^@source "\.\.\/components";\n/m
const index = fs.readFileSync(path.join(to, "index.css"), "utf8")
if ((index.match(new RegExp(SCAN_ALL.source, "gm")) ?? []).length !== 1) {
  console.error('copy-styles: expected exactly one `@source "../components";` line in styles/index.css')
  process.exit(1)
}
const lean =
  "/*\n * GENERATED by scripts/copy-styles.mjs from index.css: the same stylesheet without `@source \"../components\"`.\n" +
  " * The app lists the modules it uses with its own @source lines (see sources.json beside this file).\n */\n" +
  index.replace(SCAN_ALL, "")
fs.writeFileSync(path.join(to, "lean.css"), lean)

// ── What each module needs scanned ──────────────────────────────────────────────────────────────
// sources.json: for every module an app can import (`button`, `security/code-display`, `icon`),
// the files of this package whose classes it draws with: itself and every file it imports, all the
// way down. Paths are relative to dist/. An app turns the union for its modules into @source lines.
const dist = path.join(root, "dist")
const IMPORT = /(?:from|import)\s*["'](\.\.?\/[^"']+)["']/g
const resolveFile = (fromFile, spec) => {
  const base = path.resolve(path.dirname(fromFile), spec)
  for (const candidate of [base, `${base}.js`, path.join(base, "index.js")]) {
    if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate
  }
  return null
}
const direct = new Map()
const depsOf = (file) => {
  if (direct.has(file)) return direct.get(file)
  const found = new Set()
  direct.set(file, found)
  for (const match of fs.readFileSync(file, "utf8").matchAll(IMPORT)) {
    const target = resolveFile(file, match[1])
    // Only files under dist/ carry classes Tailwind can scan there (vendor/ has none).
    if (target && target.startsWith(dist + path.sep)) found.add(target)
  }
  return found
}
const closure = (file) => {
  const seen = new Set([file])
  const queue = [file]
  while (queue.length) {
    for (const next of depsOf(queue.pop())) {
      if (seen.has(next)) continue
      seen.add(next)
      queue.push(next)
    }
  }
  return [...seen].map((f) => path.relative(dist, f).split(path.sep).join("/")).sort()
}
const modules = {}
const add = (name, file) => {
  if (fs.existsSync(file)) modules[name] = closure(file)
}
for (const dir of ["ui", "security"]) {
  const folder = path.join(dist, "components", dir)
  for (const entry of fs.readdirSync(folder).sort()) {
    if (!entry.endsWith(".js")) continue
    const name = entry.slice(0, -3)
    add(dir === "ui" ? name : `security/${name}`, path.join(folder, entry))
  }
}
add("icon", path.join(dist, "components", "icon.js"))
add("chip", path.join(dist, "components", "chip.js"))
add("icon-button", path.join(dist, "components", "icon-button.js"))
add("check-draw", path.join(dist, "components", "check-draw.js"))
add("motion", path.join(dist, "lib", "motion", "index.js"))
fs.writeFileSync(path.join(to, "sources.json"), JSON.stringify({ $comment: "Per module: the files under dist/ to give Tailwind as @source when the app uses styles/lean.css. Generated by scripts/copy-styles.mjs.", modules }, null, 1) + "\n")
console.log(`✓ wrote dist/styles/lean.css and dist/styles/sources.json (${Object.keys(modules).length} modules)`)
